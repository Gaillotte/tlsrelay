#!/usr/bin/env bash
# cppcheck static analysis of the tlsrelay code. Fails at the first warning.
# Usage: tools/run-cppcheck.sh <build directory with compile_commands.json>
#
# Global suppressions (tools/cppcheck-suppressions.txt):
# - missingReturn: cppcheck does not recognize C++20 coroutines whose body
#   ends without co_return (asio::awaitable<void>); a real missing return is
#   already a compilation error (-Werror=return-type, MSVC C4715 with /WX);
# - system headers and dependencies.
set -euo pipefail
build=${1:?usage: $0 <build directory>}
root=$(cd "$(dirname "$0")/.." && pwd)
# Code generated by moc (*_autogen directories of the build, absent until anything
# is compiled): removed from the analyzed compilation database.
db=$(mktemp -d)
trap 'rm -rf "$db"' EXIT
python3 - "$build/compile_commands.json" "$db/compile_commands.json" <<'PY'
import json, sys
entries = json.load(open(sys.argv[1]))
json.dump([e for e in entries if "_autogen" not in e["file"]], open(sys.argv[2], "w"))
PY
cppcheck --project="$db/compile_commands.json" --file-filter="*/src/*" \
  --enable=warning,performance,portability --check-level=exhaustive --inline-suppr \
  --suppressions-list="$root/tools/cppcheck-suppressions.txt" \
  --error-exitcode=1 --quiet -j "$(nproc)"
echo "cppcheck: no warnings"
